const { PDFDocument, StandardFonts, rgb } = require('pdf-lib');
const fs = require('fs');
const W = 612, H = 792;
const pct = (x, y, w, h) => ({ x0: x / W * 100, x1: (x + w) / W * 100, yTop: (H - y - h) / H * 100, yBot: (H - y) / H * 100 });
(async () => {
  const doc = await PDFDocument.create();
  const page = doc.addPage([W, H]);
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const draw = (t, x, y, f = font, s = 11) => page.drawText(t, { x, y, size: s, font: f, color: rgb(0, 0, 0) });
  draw('Employee Information Form', 190, 745, bold, 18);
  const form = doc.getForm();
  const truthAll = JSON.parse(fs.readFileSync('positioning-truth.json'));
  const t = {};
  const addText = (name, label, x, y, w, h = 18) => {
    draw(label, x, y + h + 4, font, 10);
    const f = form.createTextField(name);
    f.addToPage(page, { x, y, width: w, height: h, borderColor: rgb(0.6, 0.65, 0.7), borderWidth: 1 });
    t[name] = pct(x, y, w, h);
  };
  addText('employee_name', 'Employee full name', 50, 660, 240);
  addText('employee_ssn', 'Social security number', 330, 660, 180);
  addText('street_address', 'Street address', 50, 600, 340);
  addText('zip_code', 'ZIP code', 420, 600, 100);
  addText('hire_date', 'Hire date (MM/DD/YYYY)', 50, 540, 150);
  addText('annual_salary', 'Annual salary', 330, 540, 150);
  const cb1 = form.createCheckBox('full_time');
  draw('Full-time employee', 76, 484, font, 10);
  cb1.addToPage(page, { x: 50, y: 478, width: 16, height: 16, borderColor: rgb(0.4, 0.45, 0.5), borderWidth: 1 });
  t['full_time'] = pct(50, 478, 16, 16);
  const cb2 = form.createCheckBox('remote_worker');
  draw('Remote worker', 256, 484, font, 10);
  cb2.addToPage(page, { x: 230, y: 478, width: 16, height: 16, borderColor: rgb(0.4, 0.45, 0.5), borderWidth: 1 });
  t['remote_worker'] = pct(230, 478, 16, 16);
  addText('emergency_contact', 'Emergency contact name and phone', 50, 410, 460);
  truthAll['acroform-form.pdf'] = t;
  fs.writeFileSync('acroform-form.pdf', await doc.save());
  fs.writeFileSync('positioning-truth.json', JSON.stringify(truthAll, null, 1));
  console.log('acroform-form.pdf with', Object.keys(t).length, 'widgets');
})();
